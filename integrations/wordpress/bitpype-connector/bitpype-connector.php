/**
 * Activation: connect this site to BitPype.
 *
 * Two cases:
 *  - A site credential is already stored (deactivation → reactivation
 *    on the same install): the credential survives deactivation, so
 *    just tell BitPype we are active again — the SAME registration
 *    resumes and the spent registration code is not involved.
 *  - No credential: spend this copy's one-time registration code.
 *    If BitPype answers that the code was already used, the local
 *    state becomes "spent" and WP admin shows the owner exactly how
 *    to get a fresh copy from their portal.
 */
function bitpype_connector_activate() {
	if ('' !== bitpype_connector_site_key()) {
		bitpype_connector_ping('active');
		if (function_exists('bitpype_connector_design_sync')) {
			bitpype_connector_design_sync();
		}
		if (function_exists('bitpype_connector_push_census')) {
			bitpype_connector_push_census();
		}
		return;
	}
	if ('spent' === (string) get_option('bitpype_link_state', '')) {
		update_option('bitpype_connector_status', 'spent');
		return;
	}
	$token = bitpype_connector_registration_token();
	if ('' === $token || false !== strpos($token, '%%')) {
		// A copy that was never generated by a portal download.
		update_option('bitpype_connector_status', 'unregistered');
		return;
	}
	bitpype_connector_register();
}
register_activation_hook(__FILE__, 'bitpype_connector_activate');

/**
 * Deactivation: tell BitPype (portal shows this site DISCONNECTED)
 * and stop rendering forms. The stored credential is KEPT, so
 * reactivating reconnects the same registration. Contacts and
 * submissions already captured live in BitPype and are unaffected.
 */
function bitpype_connector_deactivate() {
	if ('' !== bitpype_connector_site_key()) {
		bitpype_connector_disconnect('deactivated');
	}
	update_option('bitpype_connector_status', 'disconnected');
}
register_deactivation_hook(__FILE__, 'bitpype_connector_deactivate');
